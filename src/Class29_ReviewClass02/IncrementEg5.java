package Class29_ReviewClass02;

// Pre-increment (++i)
        //increase first, then use

// Post-increment (i++)
        //Use first, then increase


public class IncrementEg5 {
    static void main(String[] args) {

        int i = 10;
        int j = i++ + 10;

        System.out.println(j); // 20
        System.out.println(i); // 11

    }

}
